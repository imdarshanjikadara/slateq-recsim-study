"""Post-hoc supplementary statistics: t-based 95% intervals (df = n_seeds - 1) for every gap.

    python scripts/supplement_stats.py  ->  docs/SUPPLEMENT_STATS.md

Reads results/rq2/gaps.csv and results/rq3/gaps.csv (per-seed paired differences, diff_seed<k>).
This is SUPPLEMENTARY and POST-HOC (added 2026-11-13, after the results were seen). It does not
change any verdict: PROTOCOL 14.6 (seed-bootstrap CI excludes 0 AND all seeds share the sign)
remains the decision rule. With n = 5 seeds a percentile bootstrap over seeds can be narrower than
a t-interval, so the t-interval is shown as a more conservative cross-check.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "SUPPLEMENT_STATS.md"


def t_interval(x: np.ndarray) -> tuple[float, float, float, int]:
    n = len(x)
    m = float(np.mean(x))
    se = float(np.std(x, ddof=1)) / np.sqrt(n)
    h = float(stats.t.ppf(0.975, n - 1)) * se
    return m, m - h, m + h, n


def rows(path: Path) -> list[dict]:
    g = pd.read_csv(path)
    seed_cols = [c for c in g.columns if c.startswith("diff_seed")]
    seed_cols.sort(key=lambda c: int(c[9:]))
    out = []
    for _, r in g.iterrows():
        x = np.array([r[c] for c in seed_cols if not pd.isna(r[c])], dtype=float)
        m, lo, hi, n = t_interval(x)
        out.append(
            dict(
                condition=r.condition,
                N=int(r.num_candidates),
                k=int(r.slate_size),
                control=bool(r.control),
                comparison=r.comparison,
                n=n,
                mean=m,
                t_lo=lo,
                t_hi=hi,
                boot_lo=float(r.ci95_low),
                boot_hi=float(r.ci95_high),
                verdict=r.verdict,
                t_excludes_0=bool(lo > 0 or hi < 0),
            )
        )
    return out


def fmt(x: float) -> str:
    return f"{x:+.2f}"


def main() -> int:
    rq2 = rows(ROOT / "results" / "rq2" / "gaps.csv")
    rq3 = rows(ROOT / "results" / "rq3" / "gaps.csv")
    L = [
        "# Supplementary statistics (post-hoc)",
        "",
        "Generated by `python scripts/supplement_stats.py` from `results/rq2/gaps.csv` and "
        "`results/rq3/gaps.csv`. Do not edit by hand.",
        "",
        "**Status: post-hoc and supplementary.** Added on 2026-11-13, after the results were seen.",
        "It does **not** change any verdict: PROTOCOL 14.6 stays the decision rule (seed-bootstrap",
        "95% CI excludes 0 and all seeds share the sign). With n = 5 seeds a percentile bootstrap",
        "over seeds can be optimistic, so a t-based 95% interval (df = n - 1 = 4) is shown as a",
        "more conservative cross-check. Unit: one run seed = mean over 2400 paired eval episodes.",
        "",
    ]

    def table(title: str, rs: list[dict]) -> None:
        nonlocal L
        L += [
            f"## {title}",
            "",
            "| condition | N | k | comparison | seeds | mean | t 95% CI (df=n-1) "
            "| bootstrap 95% CI | PROTOCOL 14.6 verdict | t-CI excludes 0 |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in rs:
            ctrl = " (control)" if r["control"] else ""
            L.append(
                f"| {r['condition']} | {r['N']} | {r['k']}{ctrl} | {r['comparison']} | {r['n']} | "
                f"{fmt(r['mean'])} | [{fmt(r['t_lo'])}, {fmt(r['t_hi'])}] | "
                f"[{fmt(r['boot_lo'])}, {fmt(r['boot_hi'])}] | {r['verdict']} | "
                f"{'yes' if r['t_excludes_0'] else 'no'} |"
            )
        L.append("")

    prim = "SlateQ - learned-myopic"
    p2 = [r for r in rq2 if r["comparison"] == prim]
    grid = [r for r in p2 if not r["control"]]
    L += [
        "## Summary",
        "",
        f"- RQ2 primary gap (SlateQ - learned-myopic): t-interval excludes 0 in "
        f"**{sum(r['t_excludes_0'] for r in grid)} of {len(grid)}** grid cells.",
    ]
    for r in p2:
        if r["control"]:
            L.append(
                f"- Control cell ({r['N']},{r['k']}): mean {fmt(r['mean'])}, t-interval "
                f"[{fmt(r['t_lo'])}, {fmt(r['t_hi'])}] -> excludes 0: "
                f"{'yes' if r['t_excludes_0'] else 'no'}."
            )
    for r in [r for r in rq3 if r["comparison"] == prim]:
        L.append(
            f"- RQ3 {r['condition']}: mean {fmt(r['mean'])}, t-interval "
            f"[{fmt(r['t_lo'])}, {fmt(r['t_hi'])}] -> excludes 0: "
            f"{'yes' if r['t_excludes_0'] else 'no'} (PROTOCOL verdict: {r['verdict']})."
        )
    agree = [r for r in rq2 + rq3 if (r["verdict"] in ("A higher", "A lower")) != r["t_excludes_0"]]
    L += [
        f"- Rows where 'PROTOCOL verdict is clear' and 't-CI excludes 0' disagree: **{len(agree)}**"
        + (
            " ("
            + "; ".join(f"{r['condition']} ({r['N']},{r['k']}) {r['comparison']}" for r in agree)
            + ")"
            if agree
            else ""
        )
        + ".",
        "",
    ]
    table("RQ1/RQ2 (results/rq2/gaps.csv)", rq2)
    table("RQ3 (results/rq3/gaps.csv)", rq3)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
